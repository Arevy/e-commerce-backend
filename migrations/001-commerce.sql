-- Empty-schema baseline only. Applied by provision-platform.cjs. Never a reset.
-- Categories
CREATE TABLE CATEGORIES (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME         VARCHAR2(255) NOT NULL UNIQUE,
  DESCRIPTION  VARCHAR2(500)
);

-- Products
CREATE TABLE PRODUCTS (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME         VARCHAR2(255) NOT NULL,
  PRICE        NUMBER(10, 2) NOT NULL,
  DESCRIPTION  VARCHAR2(500),
  CATEGORY_ID  NUMBER,
  IMAGE_FILENAME VARCHAR2(255),
  IMAGE_MIME_TYPE VARCHAR2(128),
  IMAGE_DATA   BLOB,
  IMAGE_UPDATED_AT TIMESTAMP,
  CONSTRAINT CK_PRODUCTS_PRICE CHECK (PRICE >= 0),
  CONSTRAINT FK_PRODUCTS_CATEGORIES
    FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES (ID)
);

-- Users
CREATE TABLE USERS (
  ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMAIL     VARCHAR2(255) NOT NULL UNIQUE,
  PASSWORD  VARCHAR2(255) NOT NULL,
  NAME      VARCHAR2(255),
  ROLE      VARCHAR2(32) DEFAULT 'CUSTOMER' NOT NULL,
  CONSTRAINT CK_USERS_ROLE CHECK (ROLE IN ('CUSTOMER', 'SUPPORT'))
);

-- Addresses
CREATE TABLE ADDRESSES (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID     NUMBER NOT NULL,
  STREET      VARCHAR2(255) NOT NULL,
  CITY        VARCHAR2(255) NOT NULL,
  POSTAL_CODE VARCHAR2(20) NOT NULL,
  COUNTRY     VARCHAR2(100) NOT NULL,
  CONSTRAINT FK_ADDRESSES_USERS
    FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE
);

-- Orders
CREATE TABLE ORDERS (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID    NUMBER NOT NULL,
  TOTAL      NUMBER(12, 2) NOT NULL,
  STATUS     VARCHAR2(50) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT CK_ORDERS_TOTAL CHECK (TOTAL >= 0),
  CONSTRAINT FK_ORDERS_USERS
    FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

-- Order items
CREATE TABLE ORDER_ITEMS (
  ORDER_ID   NUMBER NOT NULL,
  PRODUCT_ID NUMBER NOT NULL,
  QUANTITY   NUMBER NOT NULL,
  PRICE      NUMBER(10, 2) NOT NULL,
  CONSTRAINT PK_ORDER_ITEMS PRIMARY KEY (ORDER_ID, PRODUCT_ID),
  CONSTRAINT CK_ORDER_ITEMS_QUANTITY CHECK (QUANTITY > 0 AND QUANTITY = TRUNC(QUANTITY)),
  CONSTRAINT CK_ORDER_ITEMS_PRICE CHECK (PRICE >= 0),
  CONSTRAINT FK_ORDER_ITEMS_ORDERS
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ID) ON DELETE CASCADE,
  CONSTRAINT FK_ORDER_ITEMS_PRODUCTS
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (ID)
);

-- Cart
CREATE TABLE CART_ITEMS (
  USER_ID    NUMBER NOT NULL,
  PRODUCT_ID NUMBER NOT NULL,
  QUANTITY   NUMBER NOT NULL,
  CONSTRAINT PK_CART_ITEMS PRIMARY KEY (USER_ID, PRODUCT_ID),
  -- Zero is allowed for the cart MERGE, which atomically removes rows with zero quantity.
  CONSTRAINT CK_CART_ITEMS_QUANTITY CHECK (QUANTITY >= 0 AND QUANTITY = TRUNC(QUANTITY)),
  CONSTRAINT FK_CART_ITEMS_USERS
    FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
  CONSTRAINT FK_CART_ITEMS_PRODUCTS
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (ID)
);

-- Wishlist
CREATE TABLE WISHLIST (
  USER_ID    NUMBER NOT NULL,
  PRODUCT_ID NUMBER NOT NULL,
  CONSTRAINT PK_WISHLIST PRIMARY KEY (USER_ID, PRODUCT_ID),
  CONSTRAINT FK_WISHLIST_USERS
    FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
  CONSTRAINT FK_WISHLIST_PRODUCTS
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (ID)
);

-- CMS Pages
CREATE TABLE CMS_PAGES (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SLUG         VARCHAR2(150) NOT NULL UNIQUE,
  TITLE        VARCHAR2(255) NOT NULL,
  EXCERPT      VARCHAR2(500),
  BODY         CLOB NOT NULL,
  STATUS       VARCHAR2(32) DEFAULT 'DRAFT' NOT NULL,
  PUBLISHED_AT TIMESTAMP,
  UPDATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT CK_CMS_STATUS CHECK (STATUS IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

-- Reviews
CREATE TABLE REVIEWS (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PRODUCT_ID  NUMBER NOT NULL,
  USER_ID     NUMBER NOT NULL,
  RATING      NUMBER NOT NULL,
  REVIEW_TEXT VARCHAR2(1000),
  CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT  TIMESTAMP,
  CONSTRAINT CK_REVIEWS_RATING CHECK (RATING BETWEEN 1 AND 5 AND RATING = TRUNC(RATING)),
  CONSTRAINT FK_REVIEWS_PRODUCTS
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (ID) ON DELETE CASCADE,
  CONSTRAINT FK_REVIEWS_USERS
    FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE
);

-- Payments
CREATE TABLE PAYMENTS (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ORDER_ID   NUMBER NOT NULL,
  AMOUNT     NUMBER(12, 2) NOT NULL,
  METHOD     VARCHAR2(50) NOT NULL,
  STATUS     VARCHAR2(50) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT CK_PAYMENTS_AMOUNT CHECK (AMOUNT >= 0),
  CONSTRAINT FK_PAYMENTS_ORDERS
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ID) ON DELETE CASCADE
);


